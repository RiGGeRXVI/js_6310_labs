export async function rulesCommand(ctx) {
  const text =
    'Правила игры "Змейка":\n\n' +
    '1. Игрок управляет змейкой и должен собирать фрукты.\n' +
    '2. Каждый собранный фрукт увеличивает длину змейки.\n' +
    '3. Если змейка врезается в себя, другую змейку или стенку — игра окончена.\n' +
    '4. Цель — победить остальных змеек или быть самой длинной змейкой по истечении таймера.';
  await ctx.reply(text);
}
